using Microsoft.Maui.Controls.Shapes;

namespace Himo.Views;

/// <summary>
/// Reusable, scrollable legal-document layout used by registration.
/// The content must be reviewed against the production service and applicable law before release.
/// </summary>
internal abstract class LegalDocumentPageBase : ContentPage
{
    protected LegalDocumentPageBase(
        string title,
        string subtitle,
        string iconSource,
        IReadOnlyList<(string Heading, string Body)> sections)
    {
        Title = title;
        FlowDirection = FlowDirection.RightToLeft;
        NavigationPage.SetHasNavigationBar(this, false);
        BackgroundColor = ThemeColor("HimoBackground", Color.FromArgb("#10091A"));

        var iconFrame = new Border
        {
            WidthRequest = 54,
            HeightRequest = 54,
            Padding = 12,
            BackgroundColor = ThemeColor("HimoInput", Color.FromArgb("#21172C")),
            Stroke = new SolidColorBrush(ThemeColor("HimoBorder", Color.FromArgb("#3B2B50"))),
            StrokeThickness = 1,
            StrokeShape = new RoundRectangle { CornerRadius = 17 },
            Content = new Image
            {
                Source = iconSource,
                Aspect = Aspect.AspectFit,
                HorizontalOptions = LayoutOptions.Center,
                VerticalOptions = LayoutOptions.Center
            }
        };

        var titleLabel = new Label
        {
            Text = title,
            FontSize = 23,
            FontAttributes = FontAttributes.Bold,
            TextColor = ThemeColor("HimoPrimary", Colors.White),
            HorizontalTextAlignment = TextAlignment.Start,
            LineBreakMode = LineBreakMode.WordWrap
        };

        var subtitleLabel = new Label
        {
            Text = subtitle,
            FontSize = 13,
            TextColor = ThemeColor("HimoTextSecondary", Color.FromArgb("#C5B9D4")),
            HorizontalTextAlignment = TextAlignment.Start,
            LineBreakMode = LineBreakMode.WordWrap
        };

        var titleText = new VerticalStackLayout
        {
            Spacing = 4,
            VerticalOptions = LayoutOptions.Center,
            Children = { titleLabel, subtitleLabel }
        };

        var header = new Grid
        {
            ColumnDefinitions = new ColumnDefinitionCollection
            {
                new(GridLength.Auto), new(GridLength.Star)
            },
            ColumnSpacing = 14,
            FlowDirection = FlowDirection.RightToLeft,
            Children = { iconFrame, titleText }
        };
        Grid.SetColumn(titleText, 1);

        var draftNotice = new Border
        {
            Padding = new Thickness(12, 10),
            BackgroundColor = ThemeColor("HimoInput", Color.FromArgb("#21172C")),
            Stroke = new SolidColorBrush(ThemeColor("HimoBorder", Color.FromArgb("#3B2B50"))),
            StrokeThickness = 1,
            StrokeShape = new RoundRectangle { CornerRadius = 13 },
            Content = new Label
            {
                Text = "اقرأ البنود كاملة قبل المتابعة",
                FontSize = 12,
                TextColor = ThemeColor("HimoTextSecondary", Color.FromArgb("#C5B9D4")),
                HorizontalTextAlignment = TextAlignment.Start
            }
        };

        var documentStack = new VerticalStackLayout { Spacing = 12 };
        foreach (var section in sections)
        {
            var sectionTitle = new Label
            {
                Text = section.Heading,
                FontSize = 15,
                FontAttributes = FontAttributes.Bold,
                TextColor = ThemeColor("HimoPrimary", Colors.White),
                HorizontalTextAlignment = TextAlignment.Start
            };
            var sectionBody = new Label
            {
                Text = section.Body,
                FontSize = 13.5,
                LineHeight = 1.4,
                TextColor = ThemeColor("HimoTextSecondary", Color.FromArgb("#C5B9D4")),
                HorizontalTextAlignment = TextAlignment.Start,
                VerticalTextAlignment = TextAlignment.Start
            };
            var sectionCard = new Border
            {
                Padding = new Thickness(16, 15),
                BackgroundColor = ThemeColor("HimoCard", Color.FromArgb("#21172C")),
                Stroke = new SolidColorBrush(ThemeColor("HimoBorder", Color.FromArgb("#3B2B50"))),
                StrokeThickness = 1,
                StrokeShape = new RoundRectangle { CornerRadius = 17 },
                Content = new VerticalStackLayout
                {
                    Spacing = 7,
                    Children = { sectionTitle, sectionBody }
                }
            };
            documentStack.Children.Add(sectionCard);
        }

        var documentScroll = new ScrollView
        {
            Content = documentStack,
            VerticalScrollBarVisibility = ScrollBarVisibility.Never
        };

        var backButton = new Button
        {
            Text = "العودة إلى إنشاء الحساب",
            HeightRequest = 50,
            CornerRadius = 15,
            FontAttributes = FontAttributes.Bold,
            FontSize = 14,
            TextColor = ThemeColor("HimoPrimary", Colors.White),
            BackgroundColor = ThemeColor("HimoCard", Color.FromArgb("#21172C")),
            BorderColor = ThemeColor("HimoBorder", Color.FromArgb("#3B2B50")),
            BorderWidth = 1,
            HorizontalOptions = LayoutOptions.Fill
        };
        backButton.Clicked += BackClicked;

        var contentLayout = new Grid
        {
            Padding = new Thickness(20, 18),
            RowDefinitions = new RowDefinitionCollection
            {
                new(GridLength.Auto), new(GridLength.Auto), new(GridLength.Star), new(GridLength.Auto)
            },
            RowSpacing = 12,
            Children = { header, draftNotice, documentScroll, backButton }
        };
        Grid.SetRow(draftNotice, 1);
        Grid.SetRow(documentScroll, 2);
        Grid.SetRow(backButton, 3);
        Content = contentLayout;
    }

    private async void BackClicked(object? sender, EventArgs e)
    {
        if (Navigation is not null && Navigation.NavigationStack.Count > 1)
            await Navigation.PopAsync(animated: true);
    }

    private static Color ThemeColor(string key, Color fallback)
    {
        var resources = Application.Current?.Resources;
        return resources is not null && resources.TryGetValue(key, out var value) && value is Color color
            ? color
            : fallback;
    }
}

